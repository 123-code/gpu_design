#!/usr/bin/env python3
"""Generate a tensor-core test: kernel, data payload, expected results.

    python3 gen_mma_test.py <kind> [--seed N] [--out PREFIX]

Writes PREFIX.asm (the kernel), PREFIX.data.hex (payload, one byte per line)
and PREFIX.expect.hex (the bytes the kernel must leave in main memory at
RESULT_BASE). test/tb_mma.sv streams the payload in, runs the kernel on both
cores, and compares.

The kernel (1 warp of 4 lanes):
  1. copies the payload's operand tiles from main memory into shared memory
     (LDR two bytes, STS one halfword)
  2. TCFG kind; then three MMAs:
        tile 0:  D0  = A0*B0        (overwrite)
        tile 0:  D0 += A1*B1        (accumulate; waits for the first)
        tile 1:  D1  = A1*B0        (overwrite, different TMEM tile)
  3. reads both tiles back with TLD (lane i = row i), storing each D[i][j]
     as 4 little-endian bytes at RESULT_BASE + 16*col + 4*i (col = 0..7),
     then TLDQ of tile 0 (requantized bytes) at RESULT_BASE + 128 + 4*j + i.

Payload layout (main memory and shared memory alike):
   0: A0 (4 words)   16: A0 scales (mxf4)   32: B0   48: B0 scales
  64: A1             80: A1 scales          96: B1  112: B1 scales
"""
import argparse
import random
import tc_ref as tc

RESULT_BASE = 256
QSHIFT = {0: 6, 1: 9, 2: 9, 3: 9}


def tile_bytes(words):
    out = []
    for w in words:
        out += [(w >> (8 * b)) & 0xFF for b in range(4)]
    return out


def gen(kind, seed):
    rng = random.Random(seed)
    A0 = [tc.random_word(rng, kind) for _ in range(4)]
    B0 = [tc.random_word(rng, kind) for _ in range(4)]
    A1 = [tc.random_word(rng, kind) for _ in range(4)]
    B1 = [tc.random_word(rng, kind) for _ in range(4)]
    if kind == 3:
        # E8M0 scales around 2^0; the spread (sa+sb-248 in [-28, 42]) also
        # drives the hardware's [-24, 24] shift clamp from both sides
        sc = lambda: [rng.randrange(110, 145) for _ in range(4)]
        sA0, sB0, sA1, sB1 = sc(), sc(), sc(), sc()
    else:
        sA0 = sB0 = sA1 = sB1 = [127] * 4

    data = [0] * 128
    for base, words, scales in ((0, A0, sA0), (32, B0, sB0), (64, A1, sA1), (96, B1, sB1)):
        data[base:base + 16] = tile_bytes(words)
        data[base + 16:base + 20] = scales

    Z = [[0] * 4 for _ in range(4)]
    D0 = tc.mma(Z, A0, B0, kind, False, sA0, sB0)
    D0 = tc.mma(D0, A1, B1, kind, True, sA1, sB1)
    D1 = tc.mma(Z, A1, B0, kind, False, sA1, sB0)

    expect = [0] * 144
    for t, D in enumerate((D0, D1)):
        for j in range(4):
            for i in range(4):
                v = D[i][j] & 0xFFFFFFFF
                a = 16 * (4 * t + j) + 4 * i
                expect[a:a + 4] = [(v >> (8 * b)) & 0xFF for b in range(4)]
    for j in range(4):
        for i in range(4):
            expect[128 + 4 * j + i] = tc.tldq(D0[i][j], QSHIFT[kind])
    return data, expect


def kernel(kind, tma=False):
    q = QSHIFT[kind]
    L = []
    e = L.append
    e(f"// generated by gen_mma_test.py: tensor core test, kind {kind}"
      + (", operands staged by the TMA" if tma else ""))
    e("        TID  R1")
    if tma:
        return kernel_tma(kind, q, L)
    # 1. copy 128 payload bytes -> shared, 64 halfwords, 16 per lane:
    #    lane copies halfwords h = tid, tid+4, ... (byte address 2h)
    e("        ADD  R2, R1, R1       // R2 = byte address 2*tid")
    e("        MOV  R6, #8")
    e("        MOV  R0, #0           // R0 = iteration")
    e("        MOV  R7, #16")
    e("copy:   LDR  R3, [R2]         // low byte")
    e("        ADDI R4, R2, #1")
    e("        LDR  R4, [R4]         // high byte")
    e("        SHL  R4, R4, R6")
    e("        ADD  R3, R3, R4")
    e("        STS  R3, [R2]")
    e("        ADDI R2, R2, #8       // next halfword of this lane")
    e("        ADDI R0, R0, #1")
    e("        CMP  R0, R7")
    e("        BRn  copy")
    # 2. configure + MMAs (issued by lane 0; operand addresses are uniform)
    e(f"        MOV  R0, #{(q << 3) | kind}")
    e("        TCFG R0               // kind + TLDQ shift")
    e("        MOV  R2, #0           // A0")
    e("        MOV  R3, #32          // B0")
    e("        MMA  R2, R3, #0, #0   // D0  = A0*B0")
    e("        LDI  R5, #64          // A1")
    e("        LDI  R4, #96          // B1")
    e("        MMA  R5, R4, #0, #1   // D0 += A1*B1 (waits for the unit)")
    e("        MMA  R5, R3, #1, #0   // D1  = A1*B0")
    return readback(L, q)


def kernel_tma(kind, q, L):
    """Same MMAs, but the copy engine stages the operands, and the second
    pair of tiles streams in WHILE the first MMA runs."""
    e = L.append
    e(f"        MOV  R0, #{(q << 3) | kind}")
    e("        TCFG R0")
    e("        MOV  R2, #0")
    e("        MOV  R3, #32")
    e("        TMA  R2, R2, #8       // A0 (+scales): data[0..31]  -> shared[0..31]")
    e("        TMA  R3, R3, #8       // B0 (+scales): data[32..63] -> shared[32..63]")
    e("        TMAWAIT")
    e("        MMA  R2, R3, #0, #0   // D0  = A0*B0  (async)")
    e("        LDI  R5, #64")
    e("        LDI  R4, #96")
    e("        TMA  R5, R5, #8       // A1 streams in while the MMA runs")
    e("        TMA  R4, R4, #8       // B1")
    e("        TMAWAIT")
    e("        MMA  R5, R4, #0, #1   // D0 += A1*B1")
    e("        MMA  R5, R3, #1, #0   // D1  = A1*B0")
    return readback(L, q)


def readback(L, q):
    e = L.append
    # 3. readback
    e("        ADD  R4, R1, R1")
    e("        ADD  R4, R4, R4       // R4 = 4*tid")
    e("        MOV  R7, #8")
    e("        WBASE #63")
    e("        WBASE #63")
    e("        WBASE #63")
    e("        WBASE #63")
    e("        WBASE #4              // wbase = 256 = RESULT_BASE")
    for col in range(8):
        e(f"        TLD  R3, #{col}, #0    // D[tid][{col % 4}] of tile {col // 4}, low half")
        e(f"        TLD  R5, #{col}, #1    // high half")
        e("        STR  R3, [R4]")
        e("        SHR  R3, R3, R7")
        e("        ADDI R6, R4, #1")
        e("        STR  R3, [R6]")
        e("        ADDI R6, R4, #2")
        e("        STR  R5, [R6]")
        e("        SHR  R5, R5, R7")
        e("        ADDI R6, R4, #3")
        e("        STR  R5, [R6]")
        e("        WBASE #16")
    # TLDQ of tile 0 at RESULT_BASE + 128 + 4*j + tid  (wbase is +128 now)
    for j in range(4):
        e(f"        TLDQ R3, #{j}")
        e(f"        ADDI R6, R1, #{4 * j}")
        e("        STR  R3, [R6]")
    e("        RET")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("kind", choices=list(tc.KINDS))
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default=None)
    ap.add_argument("--tma", action="store_true", help="stage operands with TMA")
    a = ap.parse_args()
    kind = tc.KINDS[a.kind]
    out = a.out or f"build/mma_{a.kind}"
    data, expect = gen(kind, a.seed)
    open(out + ".asm", "w").write(kernel(kind, a.tma))
    open(out + ".data.hex", "w").write("\n".join(f"{b:02x}" for b in data) + "\n")
    open(out + ".expect.hex", "w").write("\n".join(f"{b:02x}" for b in expect) + "\n")
    print(f"wrote {out}.asm/.data.hex/.expect.hex (kind {a.kind}, seed {a.seed})")
