#!/usr/bin/env python3
"""Generate the global-memory (SDRAM) test: kernel, payload, expected bytes.

    python3 gen_global_test.py [--seed N] [--out PREFIX]

The payload goes to GLOBAL memory (send_kernel.py --global), which both
cores share. A grid of GRID blocks (1 warp of 4 lanes each) then:

  1. LDG/STG through the L1: lane t of block b loads halfword
     h[t + 4*(b % 2)] from global 128+..., loads it AGAIN (an L1 hit), and
     stores 2*h + b to global 512 + 16*b + 2*t.
  2. TMAG: the copy engine pulls the four operand tiles from global memory
     into shared memory (the second pair while the first MMA runs), two
     int8 MMAs accumulate D0 = A0*B0 + A1*B1, and every lane stores its row
     of D0 to global 1024 + 128*b + 16*j + 4*i (4 bytes, little-endian).

PREFIX.expect.hex holds global bytes EXPECT_BASE .. EXPECT_BASE+EXPECT_LEN-1
(untouched bytes are 0: the SDRAM model powers up cleared).
"""
import argparse
import random
import tc_ref as tc

GRID = 4
EXPECT_BASE, EXPECT_LEN = 512, 1024 + 128 * GRID - 512


def gen(seed):
    rng = random.Random(seed)
    tiles = [[tc.random_word(rng, 0) for _ in range(4)] for _ in range(4)]  # A0 B0 A1 B1
    halves = [rng.randrange(1 << 15) for _ in range(8)]
    data = [0] * 144
    for t, words in enumerate(tiles):
        for w, word in enumerate(words):
            for b in range(4):
                data[32 * t + 4 * w + b] = (word >> (8 * b)) & 0xFF
    for k, h in enumerate(halves):
        data[128 + 2 * k] = h & 0xFF
        data[129 + 2 * k] = h >> 8

    A0, B0, A1, B1 = tiles
    Z = [[0] * 4 for _ in range(4)]
    D0 = tc.mma(tc.mma(Z, A0, B0, 0, False), A1, B1, 0, True)

    mem = {}
    for b in range(GRID):
        for t in range(4):
            v = (2 * halves[t + 4 * (b % 2)] + b) & 0xFFFF
            a = 512 + 16 * b + 2 * t
            mem[a], mem[a + 1] = v & 0xFF, v >> 8
            for j in range(4):
                d = D0[t][j] & 0xFFFFFFFF
                a = 1024 + 128 * b + 16 * j + 4 * t
                for k in range(4):
                    mem[a + k] = (d >> (8 * k)) & 0xFF
    expect = [mem.get(EXPECT_BASE + i, 0) for i in range(EXPECT_LEN)]
    return data, expect


KERNEL = """// generated by gen_global_test.py: global memory, L1, TMAG
        TID  R1
        BID  R2
        // ---- 1. LDG twice (miss, then L1 hit), STG 2*h + bid ----
        MOV  R6, #1
        AND_PLACEHOLDER
        ADD  R3, R3, R1          // index t + 4*(bid % 2)
        ADD  R3, R3, R3          // byte offset
        LDI  R4, #128
        ADD  R3, R3, R4          // R3 = &h[...]
        LDG  R4, [R3]            // miss: the line comes from SDRAM
        LDG  R5, [R3]            // hit
        ADD  R4, R4, R5
        ADD  R4, R4, R2          // 2*h + bid
        MOV  R6, #4
        SHL  R5, R2, R6          // 16*bid
        ADD  R5, R5, R1
        ADD  R5, R5, R1          // + 2*t
        LDI  R6, #512
        ADD  R5, R5, R6
        STG  R4, [R5]
        // ---- 2. TMAG the tiles from global, two MMAs ----
        MOV  R0, #0
        TCFG R0                  // s8
        MOV  R2, #0
        MOV  R3, #32
        LDI  R4, #64
        LDI  R5, #96
        TMAG R2, R2, #8          // A0: global[0..31]  -> shared[0..31]
        TMAG R3, R3, #8          // B0
        TMAWAIT
        MMA  R2, R3, #0, #0      // D0 = A0*B0 (async)
        TMAG R4, R4, #8          // A1 streams in during the MMA
        TMAG R5, R5, #8          // B1
        TMAWAIT
        MMA  R4, R5, #0, #1      // D0 += A1*B1
        // ---- 3. each lane stores its row of D0 to global ----
        BID  R2
        MOV  R6, #7
        SHL  R3, R2, R6          // 128*bid
        ADD  R3, R3, R1
        ADD  R3, R3, R1
        ADD  R3, R3, R1
        ADD  R3, R3, R1          // + 4*t
        LDI  R6, #1024
        ADD  R3, R3, R6          // R3 = row base for column 0
"""


def kernel():
    k = KERNEL
    # bid % 2 * 4 without AND: (bid - 2*(bid>>1)) << 2
    k = k.replace("        AND_PLACEHOLDER\n",
                  "        SHR  R3, R2, R6\n"
                  "        SHL  R3, R3, R6\n"
                  "        SUB  R3, R2, R3          // bid % 2\n"
                  "        MOV  R6, #2\n"
                  "        SHL  R3, R3, R6          // 4*(bid % 2)\n")
    for j in range(4):
        k += f"        TLD  R4, #{j}, #0\n"
        k += f"        TLD  R5, #{j}, #1\n"
        k += "        STG  R4, [R3]\n"
        k += "        ADDI R3, R3, #2\n"
        k += "        STG  R5, [R3]\n"
        k += "        ADDI R3, R3, #14         // next column\n"
    k += "        RET\n"
    return k


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default="build/global")
    a = ap.parse_args()
    data, expect = gen(a.seed)
    open(a.out + ".asm", "w").write(kernel())
    open(a.out + ".data.hex", "w").write("\n".join(f"{b:02x}" for b in data) + "\n")
    open(a.out + ".expect.hex", "w").write("\n".join(f"{b:02x}" for b in expect) + "\n")
    print(f"wrote {a.out}.asm/.data.hex/.expect.hex")
