#!/usr/bin/env python3
"""Generate the cluster test: kernel, payload, expected bytes per core.

    python3 gen_cluster_test.py <kind> [--seed N] [--out PREFIX]

A cluster launch of 2 blocks (one pair, rank = blockIdx & 1), 1 warp of 4
lanes each. Every lane t of rank r:
  1. DSMEM store: writes v = 100*r + t + 1 into the PEER's shared memory
     (address 0x400 | (64 + 2t)), then CBAR.
  2. Reads its OWN shared[64 + 2t] (the peer's value, 100*(1-r) + t + 1) and
     the PEER's shared[64 + 2t] by a DSMEM load (its own value back), and
     stores both to data memory at 160 + 2t and 176 + 2t.
  3. MMA2: TMA's its own A_r to shared 0 and its half of B, B_r, to shared 32;
     CBAR; MMA2 computes D_r (4x8) = A_r x [B_0 | B_1], reading the peer's
     half of B over the cluster link. Every lane stores its row of all 8
     columns to data memory at 256 + 16*col + 4*t.

Payload (broadcast to both cores' data memory):
   0: A_0 (+scales)   32: A_1   64: B_0   96: B_1
PREFIX.expect<r>.hex = bytes 160..191 and 256..383 of core r's data memory,
as one 160-byte list (160..191 first).
"""
import argparse
import random
import tc_ref as tc

QSHIFT = 6


def gen(kind, seed):
    rng = random.Random(seed)
    A = [[tc.random_word(rng, kind) for _ in range(4)] for _ in range(2)]
    B = [[tc.random_word(rng, kind) for _ in range(4)] for _ in range(2)]
    if kind == 3:
        sc = lambda: [rng.randrange(115, 140) for _ in range(4)]
        sA, sB = [sc(), sc()], [sc(), sc()]
    else:
        sA = sB = [[127] * 4, [127] * 4]
    data = [0] * 128
    for base, words, scales in ((0, A[0], sA[0]), (32, A[1], sA[1]), (64, B[0], sB[0]), (96, B[1], sB[1])):
        for w, word in enumerate(words):
            for b in range(4):
                data[base + 4 * w + b] = (word >> (8 * b)) & 0xFF
        data[base + 16:base + 20] = scales

    Z = [[0] * 4 for _ in range(4)]
    expect = []
    for r in range(2):
        e = [0] * 160
        for t in range(4):
            mine, peer = 100 * r + t + 1, 100 * (1 - r) + t + 1
            e[2 * t], e[2 * t + 1] = peer & 0xFF, peer >> 8          # own shared slot
            e[16 + 2 * t], e[17 + 2 * t] = mine & 0xFF, mine >> 8    # peer's slot, DSMEM load
        left = tc.mma(Z, A[r], B[0], kind, False, sA[r], sB[0])
        right = tc.mma(Z, A[r], B[1], kind, False, sA[r], sB[1])
        for col in range(8):
            D = left if col < 4 else right
            for i in range(4):
                v = D[i][col % 4] & 0xFFFFFFFF
                a = 32 + 16 * col + 4 * i
                e[a:a + 4] = [(v >> (8 * k)) & 0xFF for k in range(4)]
        expect.append(e)
    return data, expect


def kernel(kind):
    k = f"""// generated by gen_cluster_test.py: DSMEM, CBAR, MMA2 (kind {kind})
        TID   R1
        CRANK R2
        // rank 1 dawdles first, so without a real cluster barrier rank 0
        // would read its shared memory before rank 1 has stored into it
        MOV   R6, #40
        MUL   R7, R6, R2            // 40 * rank iterations
        MOV   R6, #0
        MOV   R5, #1
dly:    CMP   R6, R7
        BRzp  dlyd
        ADD   R6, R6, R5
        BR    dly
dlyd:
        // ---- 1. store v = 100*rank + tid + 1 into the PEER's shared memory ----
        LDI   R3, #100
        MUL   R3, R3, R2
        ADD   R3, R3, R1
        ADDI  R3, R3, #1
        ADD   R4, R1, R1            // R4 = 2*tid
        LDI   R5, #{0x400 + 64}     // bit 10: the peer's shared memory
        ADD   R5, R5, R4
        STS   R3, [R5]
        CBAR                        // both blocks' stores are done past here
        // ---- 2. own slot (written by the peer), and the peer's slot by DSMEM ----
        LDI   R6, #64
        ADD   R6, R6, R4
        LDS   R0, [R6]              // = 100*(1-rank) + tid + 1
        LDS   R3, [R5]              // DSMEM load: = 100*rank + tid + 1
        WBASE #63                   // wbase = 160 (clear of the payload at 0..127)
        WBASE #63
        WBASE #34
        MOV   R7, #8
        STR   R0, [R4]
        SHR   R0, R0, R7
        ADDI  R6, R4, #1
        STR   R0, [R6]
        ADDI  R6, R4, #16
        STR   R3, [R6]
        SHR   R3, R3, R7
        ADDI  R6, R4, #17
        STR   R3, [R6]
        // ---- 3. MMA2: own A, own half of B, the peer's half over the link ----
        LDI   R0, #{(QSHIFT << 3) | kind}
        TCFG  R0
        MOV   R6, #5
        SHL   R3, R2, R6            // 32*rank
        MOV   R5, #0
        TMA   R3, R5, #8            // A_rank -> shared[0..31]
        ADDI  R3, R3, #63
        ADDI  R3, R3, #1            // 64 + 32*rank: B_rank
        MOV   R6, #32
        TMA   R3, R6, #8            // B_rank -> shared[32..63]
        TMAWAIT
        CBAR                        // the peer's half of B is in place
        MMA2  R5, R6, #0, #0        // D (tiles 0,1) = A x [B_0 | B_1]
        ADD   R4, R4, R4            // R4 = 4*tid
        MOV   R7, #8
        WBASE #63                   // wbase: 160 -> 256 (results)
        WBASE #33
"""
    for col in range(8):
        k += f"        TLD   R3, #{col}, #0\n"
        k += f"        TLD   R5, #{col}, #1\n"
        if col == 0:
            k += "        CBAR                        // MMA2 done (TLD waited): the peer may move on\n"
        k += "        STR   R3, [R4]\n"
        k += "        SHR   R3, R3, R7\n"
        k += "        ADDI  R6, R4, #1\n"
        k += "        STR   R3, [R6]\n"
        k += "        ADDI  R6, R4, #2\n"
        k += "        STR   R5, [R6]\n"
        k += "        SHR   R5, R5, R7\n"
        k += "        ADDI  R6, R4, #3\n"
        k += "        STR   R5, [R6]\n"
        k += "        WBASE #16\n"
    k += "        RET\n"
    return k


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("kind", choices=list(tc.KINDS))
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    kind = tc.KINDS[a.kind]
    out = a.out or f"build/cluster_{a.kind}"
    data, expect = gen(kind, a.seed)
    open(out + ".asm", "w").write(kernel(kind))
    open(out + ".data.hex", "w").write("\n".join(f"{b:02x}" for b in data) + "\n")
    for r in range(2):
        open(out + f".expect{r}.hex", "w").write("\n".join(f"{b:02x}" for b in expect[r]) + "\n")
    print(f"wrote {out}.*")
